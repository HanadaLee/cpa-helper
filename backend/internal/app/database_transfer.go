// TransferSQLite only reads the source. Import requires a completely empty target;
// schema creation, copy, checksums and migration version are one atomic transaction.
// Verification is intended before reopening traffic, not against a changing server.
func TransferSQLite(ctx context.Context, source string, verifyOnly bool, out io.Writer) error {
	if migrations.PostgreSQLBaselineVersion != migrations.LatestVersion {
		return fmt.Errorf("SQLite transfer baseline is out of date; update the importer before transferring this schema")
	}
	if strings.TrimSpace(os.Getenv("CPA_HELPER_DATABASE_URL")) == "" {
		return fmt.Errorf("CPA_HELPER_DATABASE_URL must point to an empty PostgreSQL database")
	}
	path, err := filepath.Abs(source)
	if err != nil {
		return err
	}
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("source must be an existing SQLite file")
	}
	raw, err := sql.Open("sqlite", sqliteDSN(path, true))
	if err != nil {
		return err
	}
	defer raw.Close()
	raw.SetMaxOpenConns(1)
	src, err := raw.BeginTx(ctx, &sql.TxOptions{ReadOnly: true})
	if err != nil {
		return err
	}
	defer src.Rollback()
	if err := checkTransferSource(ctx, src); err != nil {
		return err
	}

	paths, err := resolveRuntimePaths()
	if err != nil {
		return err
	}
	dst, err := openRuntimeDB(paths, false)
	if err != nil {
		return err
	}
	defer dst.Close()
	if !dst.Postgres {
		return fmt.Errorf("target must be PostgreSQL")
	}
	tx, err := dst.BeginTx(ctx, &sql.TxOptions{ReadOnly: verifyOnly})
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if !verifyOnly {
		// Serialize against migrate and other imports, without retaining another connection.
		if _, err := tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(?)", postgresMigrationLock); err != nil {
			return err
		}
		var objects int
		if err := tx.QueryRowContext(ctx, "SELECT COUNT(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public'").Scan(&objects); err != nil {
			return err
		}
		if objects != 0 {
			return fmt.Errorf("target public schema is not empty; nothing was overwritten (use a new database, do not run migrate first)")
		}
		schema, err := migrations.PostgresFS.ReadFile(fmt.Sprintf("postgres/%d_baseline.sql", migrations.PostgreSQLBaselineVersion))
		if err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, string(schema)); err != nil {
			return fmt.Errorf("create target schema: %w", err)
		}
		// These rows were created above in this transaction, never pre-existing user data.
		for i := len(migrations.PostgreSQLTables) - 1; i >= 0; i-- {
			if _, err := tx.ExecContext(ctx, "DELETE FROM "+quoteSQL(migrations.PostgreSQLTables[i])); err != nil {
				return err
			}
		}
	} else {
		var version int64
		if err := tx.QueryRowContext(ctx, "SELECT MAX(version_id) FROM goose_db_version").Scan(&version); err != nil {
			return err
		}
		if version != migrations.LatestVersion {
			return fmt.Errorf("target schema version %d does not match %d", version, migrations.LatestVersion)
		}
	}
	for _, table := range migrations.PostgreSQLTables {
		columns, err := transferColumns(ctx, src, tx, table)
		if err != nil {
			return err
		}
		if !verifyOnly {
			if err := copyTransferTable(ctx, src, tx, table, columns); err != nil {
				return err
			}
		}
		sourceCount, sourceHash, err := digestTransferTable(ctx, src, table, columns, false)
		if err != nil {
			return err
		}
		targetCount, targetHash, err := digestTransferTable(ctx, tx, table, columns, true)
		if err != nil {
			return err
		}
		if sourceCount != targetCount || sourceHash != targetHash {
			return fmt.Errorf("verification failed for %s (source rows=%d, target rows=%d); transaction rolled back", table, sourceCount, targetCount)
		}
		if err := transferSequence(ctx, src, tx, table, columns, verifyOnly); err != nil {
			return err
		}
		fmt.Fprintf(out, "%s: rows=%d sha256=%s OK\n", table, sourceCount, sourceHash)
	}
	if !verifyOnly {
		if _, err := tx.ExecContext(ctx, `CREATE TABLE goose_db_version (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            version_id BIGINT NOT NULL, is_applied BOOLEAN NOT NULL,
            tstamp TIMESTAMP NOT NULL DEFAULT now())`); err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, "INSERT INTO goose_db_version(version_id,is_applied) VALUES (0,true), (?,true)", migrations.LatestVersion); err != nil {
			return err
		}
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	if !verifyOnly {
		// Planner statistics are a performance concern only; the committed import is already verified.
		if _, err := dst.ExecContext(ctx, "ANALYZE"); err != nil {
			fmt.Fprintln(out, "WARNING: import committed, ANALYZE failed; run ANALYZE before reopening traffic.")
		}
	}
	fmt.Fprintf(out, "SQLite -> PostgreSQL %s complete: %d tables verified, source unchanged.\n", map[bool]string{true: "verification", false: "import"}[verifyOnly], len(migrations.PostgreSQLTables))
	return nil
}

func checkTransferSource(ctx context.Context, src *sql.Tx) error {
	var version int64
	if err := src.QueryRowContext(ctx, "SELECT MAX(version_id) FROM goose_db_version").Scan(&version); err != nil {
		return fmt.Errorf("source schema: %w", err)
	}
	if version != migrations.LatestVersion {
		return fmt.Errorf("source schema %d must equal %d; upgrade a backed-up SQLite database with this binary first", version, migrations.LatestVersion)
	}
	var integrity string
	if err := src.QueryRowContext(ctx, "PRAGMA integrity_check").Scan(&integrity); err != nil {
		return err
	}
	if integrity != "ok" {
		return fmt.Errorf("source integrity_check failed")
	}
	rows, err := src.QueryContext(ctx, "PRAGMA foreign_key_check")
	if err != nil {
		return err
	}
	bad := rows.Next()
	rowErr := rows.Err()
	rows.Close()
	if rowErr != nil {
		return rowErr
	}
	if bad {
		return fmt.Errorf("source foreign_key_check failed; repair before migrating")
	}
	rows, err = src.QueryContext(ctx, "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name <> 'goose_db_version' ORDER BY name")
	if err != nil {
		return err
	}
	defer rows.Close()
	var actual []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return err
		}
		actual = append(actual, name)
	}
	if err := rows.Err(); err != nil {
		return err
	}
	expected := append([]string(nil), migrations.PostgreSQLTables...)
	sort.Strings(expected)
	if strings.Join(actual, ",") != strings.Join(expected, ",") {
		return fmt.Errorf("source has missing or unknown tables; refusing an incomplete transfer")
	}
	var settings int
	if err := src.QueryRowContext(ctx, "SELECT COUNT(*) FROM app_settings WHERE id=1").Scan(&settings); err != nil {
		return err
	}
	if settings != 1 {
		return ErrAppSettingsMissing
	}
	return nil
}

type transferColumn struct {
	name string
	kind string
	pk   int
}

func quoteSQL(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

func transferColumns(ctx context.Context, src *sql.Tx, dst *database.Tx, table string) ([]transferColumn, error) {
	rows, err := dst.QueryContext(ctx, "SELECT column_name, data_type FROM information_schema.columns WHERE table_schema='public' AND table_name=?", table)
	if err != nil {
		return nil, err
	}
	types := map[string]string{}
	for rows.Next() {
		var name, kind string
		if err := rows.Scan(&name, &kind); err != nil {
			rows.Close()
			return nil, err
		}
		types[name] = kind
	}
	rowErr := rows.Err()
	rows.Close()
	if rowErr != nil {
		return nil, rowErr
	}
	rows, err = src.QueryContext(ctx, "PRAGMA table_info("+quoteSQL(table)+")")
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var columns []transferColumn
	for rows.Next() {
		var cid, notNull, pk int
		var name, kind string
		var defaultValue any
		if err := rows.Scan(&cid, &name, &kind, &notNull, &defaultValue, &pk); err != nil {
			return nil, err
		}
		targetKind, ok := types[name]
		if !ok {
			return nil, fmt.Errorf("%s.%s missing in target schema", table, name)
		}
		columns = append(columns, transferColumn{name: name, kind: targetKind, pk: pk})
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	if len(columns) != len(types) {
		return nil, fmt.Errorf("%s source/target columns differ", table)
	}
	return columns, nil
}

func transferSelect(table string, columns []transferColumn, postgres bool) string {
	names := []string{}
	keys := append([]transferColumn(nil), columns...)
	sort.Slice(keys, func(i, j int) bool { return keys[i].pk < keys[j].pk })
	order := []string{}
	for _, c := range columns {
		expr := quoteSQL(c.name)
		// modernc converts declared DATETIME into time.Time. Read the exact stored text.
		if !postgres && c.kind == "text" {
			expr = "CAST(" + expr + " AS TEXT)"
		}
		names = append(names, expr)
	}
	for _, c := range keys {
		if c.pk == 0 {
			continue
		}
		expr := quoteSQL(c.name)
		if postgres && c.kind == "text" {
			expr += ` COLLATE "C"`
		}
		order = append(order, expr)
	}
	return "SELECT " + strings.Join(names, ",") + " FROM " + quoteSQL(table) + " ORDER BY " + strings.Join(order, ",")
}

func scanTransferRow(rows *sql.Rows, columns []transferColumn) ([]any, error) {
	values := make([]any, len(columns))
	pointers := make([]any, len(columns))
	for i := range values {
		pointers[i] = &values[i]
	}
	if err := rows.Scan(pointers...); err != nil {
		return nil, err
	}
	for i, v := range values {
		if v == nil {
			continue
		}
		c := columns[i]
		switch {
		case c.kind == "text":
			switch value := v.(type) {
			case []byte:
				values[i] = string(value)
			case time.Time:
				values[i] = value.Format(time.RFC3339Nano)
			}
		case c.kind == "smallint" || c.kind == "bigint" || c.kind == "integer":
			switch value := v.(type) {
			case bool:
				if value {
					values[i] = int64(1)
				} else {
					values[i] = int64(0)
				}
			}
		case c.kind == "numeric":
			var number float64
			switch value := v.(type) {
			case float64:
				number = value
			case int64:
				number = float64(value)
			case []byte:
				parsed, err := strconv.ParseFloat(string(value), 64)
				if err != nil {
					return nil, err
				}
				number = parsed
			case string:
				parsed, err := strconv.ParseFloat(value, 64)
				if err != nil {
					return nil, err
				}
				number = parsed
			default:
				return nil, fmt.Errorf("unsupported numeric value for %s", c.name)
			}
			// Both applications account using float64; canonical decimal round-trip
			// preserves the source's effective value without recomputing prices.
			values[i] = strconv.FormatFloat(number, 'g', -1, 64)
		}
	}
	return values, nil
}

func copyTransferTable(ctx context.Context, src *sql.Tx, dst *database.Tx, table string, columns []transferColumn) error {
	rows, err := src.QueryContext(ctx, transferSelect(table, columns, false))
	if err != nil {
		return err
	}
	defer rows.Close()
	names := []string{}
	for _, c := range columns {
		names = append(names, quoteSQL(c.name))
	}
	prefix := "INSERT INTO " + quoteSQL(table) + "(" + strings.Join(names, ",") + ") VALUES "
	valuesSQL := "(" + strings.TrimSuffix(strings.Repeat("?,", len(columns)), ",") + ")"
	args := []any{}
	tuples := []string{}
	batchBytes := 0
	flush := func() error {
		if len(tuples) == 0 {
			return nil
		}
		_, err := dst.ExecContext(ctx, prefix+strings.Join(tuples, ","), args...)
		args = nil
		tuples = nil
		batchBytes = 0
		if err != nil {
			return fmt.Errorf("copy %s: %w", table, err)
		}
		return nil
	}
	for rows.Next() {
		values, err := scanTransferRow(rows, columns)
		if err != nil {
			return err
		}
		args = append(args, values...)
		for _, value := range values {
			switch v := value.(type) {
			case string:
				batchBytes += len(v)
			case []byte:
				batchBytes += len(v)
			default:
				batchBytes += 16
			}
		}
		tuples = append(tuples, valuesSQL)
		if len(tuples) >= 200 || batchBytes >= 8*1024*1024 {
			if err := flush(); err != nil {
				return err
			}
		}
	}
	if err := rows.Err(); err != nil {
		return err
	}
	return flush()
}

func hashTransferValue(h hash.Hash, value any) {
	if value == nil {
		h.Write([]byte{0})
		return
	}
	h.Write([]byte{1})
	var data []byte
	if raw, ok := value.([]byte); ok {
		data = raw
	} else {
		data = []byte(fmt.Sprint(value))
	}
	var size [8]byte
	binary.BigEndian.PutUint64(size[:], uint64(len(data)))
	h.Write(size[:])
	h.Write(data)
}

func digestTransferTable(ctx context.Context, db quotaQuerier, table string, columns []transferColumn, postgres bool) (int64, string, error) {
	rows, err := db.QueryContext(ctx, transferSelect(table, columns, postgres))
	if err != nil {
		return 0, "", err
	}
	defer rows.Close()
	h := sha256.New()
	var count int64
	for rows.Next() {
		values, err := scanTransferRow(rows, columns)
		if err != nil {
			return 0, "", err
		}
		for _, v := range values {
			hashTransferValue(h, v)
		}
		count++
	}
	return count, hex.EncodeToString(h.Sum(nil)), rows.Err()
}

func transferSequence(ctx context.Context, src *sql.Tx, dst *database.Tx, table string, columns []transferColumn, verify bool) error {
	hasID := false
	for _, c := range columns {
		if c.name == "id" {
			hasID = true
		}
	}
	if !hasID {
		return nil
	}
	var sequence sql.NullString
	if err := dst.QueryRowContext(ctx, "SELECT pg_get_serial_sequence(?, 'id')", table).Scan(&sequence); err != nil {
		return err
	}
	if !sequence.Valid {
		return nil
	}
	var sourceSequence, maxID int64
	if err := src.QueryRowContext(ctx, "SELECT COALESCE(MAX(seq),0) FROM sqlite_sequence WHERE name=?", table).Scan(&sourceSequence); err != nil {
		return err
	}
	if err := src.QueryRowContext(ctx, "SELECT COALESCE(MAX(id),0) FROM "+quoteSQL(table)).Scan(&maxID); err != nil {
		return err
	}
	high := max(sourceSequence, maxID)
	if verify {
		// pg_sequences.last_value is null until the first nextval/setval.
		var current sql.NullInt64
		if err := dst.QueryRowContext(ctx, "SELECT last_value FROM pg_sequences WHERE schemaname='public' AND sequencename=?", strings.TrimPrefix(sequence.String, "public.")).Scan(&current); err != nil {
			return err
		}
		if high > 0 && (!current.Valid || current.Int64 < high) {
			return fmt.Errorf("%s identity sequence is behind source high-water mark %d", table, high)
		}
		return nil
	}
	_, err := dst.ExecContext(ctx, "SELECT setval(?::regclass, ?, ?::bigint <> 0)", sequence.String, max(high, int64(1)), high)
	return err
}
